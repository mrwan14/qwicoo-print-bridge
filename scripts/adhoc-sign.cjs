// electron-builder afterPack: ad-hoc sign the macOS app (free, no Apple account). Without it Apple
// Silicon reports the unsigned test build as "damaged". Replace with a Developer ID + notarization
// before shipping Macs to restaurants.
const { execFileSync } = require("node:child_process");
const path = require("node:path");

exports.default = async function adhocSign(context) {
  if (context.electronPlatformName !== "darwin") return;
  const app = path.join(context.appOutDir, `${context.packager.appInfo.productFilename}.app`);
  execFileSync("codesign", ["--force", "--deep", "--sign", "-", app], { stdio: "inherit" });
  execFileSync("codesign", ["--verify", "--deep", "--strict", app], { stdio: "inherit" });
  console.log(`  • ad-hoc signed ${app}`);
};
